/**
 * Build the Worker into single files.
 *
 * This used to be a plain concatenation of src/*.js, which worked while the
 * server had no dependencies: the output was readable and small enough to
 * paste into the Cloudflare dashboard editor. Reading PDF and HWPX brought in
 * `unpdf` and `fflate`, so the bundle now has to resolve node_modules, which
 * only a real bundler does. The paste route is gone at this size - see the
 * README - but both artefacts stay so the tests keep driving a built Worker
 * rather than the sources.
 */

import { build } from "esbuild";
import { readFile, mkdir } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const entry = join(here, "..", "src", "index.js");
const dist = join(here, "..", "dist");

// Workers rejects a script whose gzipped size passes this.
const GZIP_LIMIT = 3 * 1024 * 1024;

await mkdir(dist, { recursive: true });

const banner = {
  js: `// Naver Content MCP - single-file Cloudflare Worker build.
// Generated by scripts/bundle.mjs from src/*.js - edit those, not this.`,
};

const targets = [
  { out: join(dist, "worker.js"), minify: false },
  { out: join(dist, "worker.min.js"), minify: true },
];

let over = false;

for (const { out, minify } of targets) {
  await build({
    entryPoints: [entry],
    outfile: out,
    bundle: true,
    format: "esm",
    target: "es2022",
    platform: "browser",
    // Pick the package builds meant for a Worker runtime, not the Node ones.
    conditions: ["workerd", "worker", "browser", "import"],
    minify,
    legalComments: "none",
    banner: minify ? undefined : banner,
  });

  const code = await readFile(out);
  const gz = gzipSync(code).length;
  console.log(
    `wrote ${out}\n  raw  ${code.length.toLocaleString()} bytes` +
      `\n  gzip ${gz.toLocaleString()} bytes  (limit ${GZIP_LIMIT.toLocaleString()})`
  );
  if (gz > GZIP_LIMIT) {
    console.error(`  OVER THE WORKERS LIMIT by ${(gz - GZIP_LIMIT).toLocaleString()} bytes`);
    over = true;
  }
}

if (over) process.exit(1);
